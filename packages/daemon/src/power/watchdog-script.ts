/**
 * The keep-awake watchdog script (ADR 0050, "Fail-safe design for level 2"
 * items 4 to 6, #1773): a POSIX `sh` script, run by a user LaunchAgent (see
 * `watchdogPlist`), that reverts the machine-wide sleep flag while a lease
 * exists and the flag cannot be read, or the hub that set it can no longer be
 * trusted to: its lease is invalid, expired or stale, the hub is gone (a dead
 * or reused pid), or the battery is at or under the lease's revert level. It
 * is a script and not the remi binary, so an upgrade, a downgrade or a broken
 * install cannot disable it.
 *
 * The decision logic lives in the generated text below, and tests run that
 * text for real. The tool paths and the revert command are fixed when the
 * script is generated: production uses the defaults (`sudo -n` running Apple's
 * `pmset`, both from `level2-commands.ts`); tests pass their own executables.
 * There is no dry-run mode.
 *
 * Nothing writes or installs this script yet.
 */

import * as path from 'node:path';
import {
  DATE_PATH,
  DISABLESLEEP_OFF,
  IOREG_PATH,
  PLUTIL_PATH,
  PMSET_PATH,
  PS_PATH,
  SUDO_PATH,
  sudoArgv,
} from './level2-commands.ts';
import { leasePath } from './level2-lease.ts';

/** The executables the script reads system state with. */
export interface WatchdogTools {
  ioreg: string;
  pmset: string;
  plutil: string;
  ps: string;
  date: string;
}

export const DEFAULT_WATCHDOG_TOOLS: Readonly<WatchdogTools> = Object.freeze({
  ioreg: IOREG_PATH,
  pmset: PMSET_PATH,
  plutil: PLUTIL_PATH,
  ps: PS_PATH,
  date: DATE_PATH,
});

/** The deadline, in seconds, of every command the script runs to read state or move the lease. */
export const WATCHDOG_COMMAND_DEADLINE_SECONDS = 10;

/** The revert command the production script runs: `sudo -n pmset` clearing the flag. */
export function defaultRevertArgv(): string[] {
  return [SUDO_PATH, ...sudoArgv(DISABLESLEEP_OFF)];
}

/**
 * `value` as one single-quoted `sh` word. Throws for a single quote or a
 * control character (a newline included) instead of escaping them, so every
 * embedded value is plain text inside its quotes.
 */
function shWord(what: string, value: string): string {
  if (value.includes("'") || /[\u0000-\u001f\u007f]/.test(value)) {
    throw new Error(`${what} must not contain a single quote or a control character`);
  }
  return `'${value}'`;
}

function absoluteWord(what: string, value: string): string {
  if (!path.isAbsolute(value)) throw new Error(`${what} must be an absolute path: ${value}`);
  return shWord(what, value);
}

/**
 * The watchdog script for `remiHome`. `tools` and `revertArgv` default to the
 * production values; tests pass absolute paths of their own executables.
 * Throws when `remiHome` or a tool is not an absolute path, or when any
 * embedded value contains a single quote or a control character.
 */
export function buildWatchdogScript(options: {
  remiHome: string;
  tools?: WatchdogTools;
  revertArgv?: readonly string[];
}): string {
  const tools = options.tools ?? DEFAULT_WATCHDOG_TOOLS;
  const revertArgv = options.revertArgv ?? defaultRevertArgv();
  absoluteWord('the remi home', options.remiHome);
  const lease = leasePath(options.remiHome);
  const [revertCommand, ...revertArgs] = revertArgv;
  if (revertCommand === undefined) throw new Error('the revert command is empty');
  const revertWords = [
    absoluteWord('the revert command', revertCommand),
    ...revertArgs.map((arg) => shWord('a revert argument', arg)),
  ].join(' ');

  const header = `#!/bin/sh
# remi keep-awake watchdog (ADR 0050, #1773), generated by remi for one remi
# home; remi rewrites this file, so edits do not last. A user LaunchAgent runs
# it with /bin/sh at load and then at a fixed interval. It never runs as root
# and reads no configuration: the lease carries what it needs.
#
# It acts only when this remi home has a lease file. With SleepDisabled
# unreadable, it runs the revert command. With SleepDisabled set, it runs it
# when the lease is invalid, expired or stale, when the hub that wrote it is
# gone, or on battery power at or under the lease's revert level. With
# SleepDisabled clear it reverts nothing and deletes a lease that is expired,
# stale or whose hub is gone. Its only output is one line per revert and one
# per failed revert, and it always exits 0.

PATH=/usr/bin:/bin:/usr/sbin:/sbin
LC_ALL=C
TZ=UTC0
export PATH LC_ALL TZ
umask 077
set -f

LEASE_DIR=${shWord('the lease directory', path.dirname(lease))}
LEASE=${shWord('the lease path', lease)}
IOREG=${absoluteWord('ioreg', tools.ioreg)}
PMSET=${absoluteWord('pmset', tools.pmset)}
PLUTIL=${absoluteWord('plutil', tools.plutil)}
PS=${absoluteWord('ps', tools.ps)}
DATE=${absoluteWord('date', tools.date)}
DEADLINE=${WATCHDOG_COMMAND_DEADLINE_SECONDS}

# The one revert command, fixed when this script was generated.
revert_action() {
  run_bounded /dev/null ${revertWords}
}
`;

  return `${header}${WATCHDOG_BODY}`;
}

/**
 * The fixed part of the script. Every command that reads state or moves the
 * lease runs through `run_bounded`; only `mktemp` (before there is a work
 * directory) and the final cleanup run directly.
 */
const WATCHDOG_BODY = `
TAB=$(printf '\\t')

# run_bounded OUT COMMAND [ARG...]: runs the command with its standard output
# in the file OUT and kills it after DEADLINE seconds. A hung child would hold
# this run, and launchd starts no new run of a job that is still running.
# Output goes to a file, not a pipe, so nothing a killed child leaves behind
# can keep this script waiting.
run_bounded() {
  rb_out=$1
  shift
  "$@" >"$rb_out" 2>/dev/null </dev/null &
  rb_child=$!
  (
    trap 'kill "$rb_sleep" 2>/dev/null; exit 0' TERM
    sleep "$DEADLINE" &
    rb_sleep=$!
    wait "$rb_sleep"
    kill -9 "$rb_child" 2>/dev/null
  ) </dev/null >/dev/null 2>&1 &
  rb_timer=$!
  # bash reports a child killed by a signal on stderr, which is the log.
  wait "$rb_child" 2>/dev/null
  rb_status=$?
  kill "$rb_timer" 2>/dev/null
  wait "$rb_timer" 2>/dev/null
  return "$rb_status"
}

# trim TEXT: sets TRIMMED to TEXT without leading and trailing white space.
trim() {
  TRIMMED=$1
  TRIMMED=\${TRIMMED#"\${TRIMMED%%[![:space:]]*}"}
  TRIMMED=\${TRIMMED%"\${TRIMMED##*[![:space:]]}"}
}

# single_line FILE: sets LINE to the only line of FILE; fails for none or several.
single_line() {
  LINE=
  sl_count=0
  while IFS= read -r sl_line || [ -n "$sl_line" ]; do
    sl_count=$((sl_count + 1))
    LINE=$sl_line
  done <"$1"
  [ "$sl_count" -eq 1 ]
}

# is_uint TEXT: TEXT is a decimal integer of at most 16 digits, no leading zero.
is_uint() {
  case $1 in
    '' | *[!0-9]* | 0?*) return 1 ;;
  esac
  [ "\${#1}" -le 16 ]
}

# lease_field FILE KEY: sets LINE to the value of KEY as plutil prints it raw.
lease_field() {
  [ -n "$WORK" ] || return 1
  run_bounded "$WORK/field" "$PLUTIL" -extract "$2" raw -o - "$1" && single_line "$WORK/field"
}

# read_lease FILE: reads the lease into the L_ variables and succeeds only for
# a regular file (not a symlink) with version 1, a one-line hubStartTime and
# integers where integers belong. plutil prints a string of digits, or an
# array as its count, like an integer, so only readLease in remi catches those
# types. L_PID and L_STARTED keep what was read, empty when it could not be, so
# a later claim can tell this lease from a newer one.
read_lease() {
  L_VERSION= L_PID= L_HUBSTART= L_STARTED= L_EXPIRES= L_HEARTBEAT= L_STALE= L_BATTERY=
  [ -n "$WORK" ] && [ -f "$1" ] && [ ! -L "$1" ] || return 1
  lease_field "$1" hubPid && L_PID=$LINE
  lease_field "$1" startedAt && L_STARTED=$LINE
  lease_field "$1" version && L_VERSION=$LINE
  lease_field "$1" hubStartTime && L_HUBSTART=$LINE
  lease_field "$1" expiresAt && L_EXPIRES=$LINE
  lease_field "$1" heartbeatAt && L_HEARTBEAT=$LINE
  lease_field "$1" staleSeconds && L_STALE=$LINE
  lease_field "$1" revertBatteryPercent && L_BATTERY=$LINE
  [ "$L_VERSION" = 1 ] && [ -n "$L_HUBSTART" ] &&
    is_uint "$L_PID" && [ "$L_PID" -ge 1 ] &&
    is_uint "$L_STARTED" && is_uint "$L_EXPIRES" && is_uint "$L_HEARTBEAT" &&
    is_uint "$L_STALE" && is_uint "$L_BATTERY"
}

# read_flag: sets FLAG to Yes or No when exactly one line of the root domain
# names SleepDisabled, with one of those values; else to unreadable.
read_flag() {
  FLAG=unreadable
  [ -n "$WORK" ] || return 0
  run_bounded "$WORK/ioreg" "$IOREG" -r -c IOPMrootDomain -d 1 || return 0
  rf_count=0
  rf_value=unreadable
  while IFS= read -r rf_line || [ -n "$rf_line" ]; do
    case $rf_line in
      *'"SleepDisabled"'*)
        rf_count=$((rf_count + 1))
        trim "$rf_line"
        case $TRIMMED in
          '"SleepDisabled" = Yes') rf_value=Yes ;;
          '"SleepDisabled" = No') rf_value=No ;;
          *) rf_value=unreadable ;;
        esac
        ;;
    esac
  done <"$WORK/ioreg"
  if [ "$rf_count" -eq 1 ]; then FLAG=$rf_value; fi
  return 0
}

# read_now: sets NOW to the epoch seconds; fails when the clock cannot be read.
read_now() {
  NOW=
  [ -n "$WORK" ] || return 1
  run_bounded "$WORK/now" "$DATE" +%s && single_line "$WORK/now" && is_uint "$LINE" || return 1
  NOW=$LINE
}

# hub_alive: the lease's hubPid is a live process that started at hubStartTime.
# ps prints local time, and TZ=UTC0 above pins it as the hub's writer does.
hub_alive() {
  [ -n "$WORK" ] || return 1
  run_bounded "$WORK/ps" "$PS" -o lstart= -p "$L_PID" && single_line "$WORK/ps" || return 1
  trim "$LINE"
  [ "$TRIMMED" = "$L_HUBSTART" ]
}

# lease_trip: sets REASON to expired, heartbeat stale (too old, or ahead of a
# clock stepped back) or hub gone, the first that holds; to clock unreadable
# when the clock cannot be read; else to nothing.
lease_trip() {
  REASON=
  if ! read_now; then
    REASON='clock unreadable'
  elif [ "$NOW" -ge "$L_EXPIRES" ]; then
    REASON=expired
  elif [ $((NOW - L_HEARTBEAT)) -gt "$L_STALE" ] || [ "$L_HEARTBEAT" -gt $((NOW + L_STALE)) ]; then
    REASON='heartbeat stale'
  elif ! hub_alive; then
    REASON='hub gone'
  fi
}

# first_percent TEXT: sets PERCENT to the first N% token of TEXT, if any.
first_percent() {
  fp_ifs=$IFS
  IFS=" $TAB;"
  for fp_token in $1; do
    case $fp_token in
      *%)
        fp_number=\${fp_token%"%"}
        if is_uint "$fp_number"; then
          PERCENT=$fp_number
          break
        fi
        ;;
    esac
  done
  IFS=$fp_ifs
}

# battery_trip: sets REASON to battery on battery power at or under the
# lease's revert level, to battery unreadable when the source or, on battery
# power, the level cannot be read; on AC power to nothing.
battery_trip() {
  REASON=
  PERCENT=
  if [ -z "$WORK" ] || ! run_bounded "$WORK/batt" "$PMSET" -g batt; then
    REASON='battery unreadable'
    return 0
  fi
  bt_source=
  bt_first=yes
  while IFS= read -r bt_line || [ -n "$bt_line" ]; do
    if [ "$bt_first" = yes ]; then
      bt_first=no
      trim "$bt_line"
      bt_source=$TRIMMED
    elif [ -z "$PERCENT" ]; then
      first_percent "$bt_line"
    fi
  done <"$WORK/batt"
  case $bt_source in
    "Now drawing from 'AC Power'") ;;
    "Now drawing from 'Battery Power'")
      if [ -z "$PERCENT" ]; then
        REASON='battery unreadable'
      elif [ "$PERCENT" -le "$L_BATTERY" ]; then
        REASON=battery
      fi
      ;;
    *) REASON='battery unreadable' ;;
  esac
}

# stamp: sets STAMP to the UTC time for a log line.
stamp() {
  STAMP=unknown-time
  [ -n "$WORK" ] || return 0
  if run_bounded "$WORK/stamp" "$DATE" -u +%Y-%m-%dT%H:%M:%SZ && single_line "$WORK/stamp"; then
    STAMP=$LINE
  fi
}

# claim_and_delete: deletes the lease only while it still holds the hubPid and
# startedAt this run read, so a lease written since is never deleted. The lease
# is renamed aside first (one atomic step) and checked there; a lease that
# changed is linked back, unless an even newer one is already in place.
claim_and_delete() {
  CLAIM="$LEASE.watchdog-$$"
  run_bounded /dev/null mv -f "$LEASE" "$CLAIM" || return 0
  read_lease "$CLAIM"
  if [ "$L_PID" != "$SEEN_PID" ] || [ "$L_STARTED" != "$SEEN_STARTED" ]; then
    run_bounded /dev/null ln "$CLAIM" "$LEASE"
  fi
  run_bounded /dev/null rm -f "$CLAIM"
}

# revert REASON: logs one line, runs the revert command, and deletes the lease
# only when the command exited 0 and the flag now reads No; otherwise it keeps
# the lease, so the next run tries again, and logs that the revert failed.
revert() {
  stamp
  printf '%s revert %s\\n' "$STAMP" "$1"
  revert_action
  rv_status=$?
  read_flag
  if [ "$rv_status" -eq 0 ] && [ "$FLAG" = No ]; then
    claim_and_delete
  else
    stamp
    printf '%s revert failed %s\\n' "$STAMP" "$1"
  fi
}

# No lease file: nothing to do, whatever the flag reads, since the flag is not
# remi's then. Checked first, so a Mac with level 2 off runs nothing else.
[ -e "$LEASE" ] || [ -L "$LEASE" ] || exit 0

WORK=$(mktemp -d "$LEASE_DIR/watchdog-run.XXXXXX" 2>/dev/null) || WORK=
trap 'if [ -n "$WORK" ]; then rm -rf "$WORK"; fi' EXIT

if read_lease "$LEASE"; then LEASE_VALID=yes; else LEASE_VALID=no; fi
SEEN_PID=$L_PID
SEEN_STARTED=$L_STARTED
read_flag

case $FLAG in
  unreadable)
    revert 'flag unreadable'
    ;;
  No)
    # Nothing is reverted. A lease left by a crash before the enable, a failed
    # enable or a reboot is deleted, so it can never later turn into a revert
    # of a flag remi did not set. An invalid lease is left for the hub.
    if [ "$LEASE_VALID" = yes ]; then
      lease_trip
      case $REASON in
        expired | 'heartbeat stale' | 'hub gone') claim_and_delete ;;
      esac
    fi
    ;;
  Yes)
    if [ "$LEASE_VALID" = no ]; then
      revert 'lease invalid'
    else
      lease_trip
      if [ -z "$REASON" ]; then battery_trip; fi
      if [ -n "$REASON" ]; then revert "$REASON"; fi
    fi
    ;;
esac
exit 0
`;
